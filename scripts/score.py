"""Score every system on the same clips with the same normalization, and write the tables.

Input:
  data/clean/<split>.jsonl                      references
  data/clean/silence_probe.jsonl                no-speech clips (empty references)
  results/predictions/<system>.<split>.jsonl    {"id": ..., "hyp": ...} per clip
  results/predictions/<system>.silence.jsonl    same, for the no-speech clips (optional)
  results/predictions/<system>.meta.json        kind, family, checkpoint, revision, settings, hardware, timing
  configs/baselines.yaml                        the full list of course baselines
Output:
  results/scores.<split>.json                   all numbers
  results/RESULTS.<split>.md                    tables (never edited by hand)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from hrasr.config import CLEAN, ROOT  # noqa: E402
from hrasr.errors import category_recall  # noqa: E402
from hrasr.manifest import read_jsonl  # noqa: E402
from hrasr.metrics import score  # noqa: E402
from hrasr.textnorm import normalize_for_scoring  # noqa: E402

RESULTS = ROOT / "results"
PRED = RESULTS / "predictions"
HEAD = ("| System | Family | Checkpoint / setup | WER % (95% CI) | CER % (95% CI) | RTFx |\n"
        "|---|---|---|---|---|---|\n")


def pct(x: float) -> str:
    return f"{100 * x:.2f}"


def load_preds(path: Path) -> dict[str, str]:
    return {r["id"]: (r.get("hyp") or "") for r in read_jsonl(path)}


def silence_scores(pred_file: Path, probe: list[dict]) -> dict:
    hyps = load_preds(pred_file)
    missing = {r["id"] for r in probe} - set(hyps)
    if missing:
        raise SystemExit(f"{pred_file.name}: {len(missing)} no-speech clips have no prediction.")
    words = {r["id"]: len(normalize_for_scoring(hyps[r["id"]]).split()) for r in probe}
    return {"clips": len(probe), "clips_with_output": sum(1 for v in words.values() if v),
            "words_emitted": sum(words.values()),
            "seconds": round(sum(r["audio_length"] for r in probe), 2)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test", choices=["dev", "test"])
    args = ap.parse_args()

    refs = {r["id"]: r["text"] for r in read_jsonl(CLEAN / f"{args.split}.jsonl")}
    probe_path = CLEAN / "silence_probe.jsonl"
    probe = list(read_jsonl(probe_path)) if probe_path.exists() else []
    listed = yaml.safe_load((ROOT / "configs" / "baselines.yaml").read_text(encoding="utf-8"))["baselines"]
    scores: dict[str, dict] = {}

    for pred_file in sorted(PRED.glob(f"*.{args.split}.jsonl")):
        system = pred_file.name[: -len(f".{args.split}.jsonl")]
        meta = json.loads((PRED / f"{system}.meta.json").read_text(encoding="utf-8"))
        hyps = load_preds(pred_file)
        missing = set(refs) - set(hyps)
        if missing:
            raise SystemExit(f"{system}: {len(missing)} clips have no prediction; every system must use the same clips.")
        ids = sorted(refs)
        s = score([refs[i] for i in ids], [hyps[i] for i in ids])
        s["categories"] = category_recall([refs[i] for i in ids], [hyps[i] for i in ids])
        if meta.get("compute_seconds") and meta.get("audio_seconds"):
            s["rtf"] = meta["compute_seconds"] / meta["audio_seconds"]
            s["rtfx"] = meta["audio_seconds"] / meta["compute_seconds"]
        sil = PRED / f"{system}.silence.jsonl"
        if probe and sil.exists():
            s["silence"] = silence_scores(sil, probe)
        scores[system] = {**s, "meta": meta}

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"scores.{args.split}.json").write_text(json.dumps(scores, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    def row(system: str, family: str, ckpt: str) -> str:
        s = scores[system]
        rtf = f"{s['rtfx']:.1f}" if "rtfx" in s else "-"
        return (f"| {system} | {family} | {ckpt} | {pct(s['wer'])} ({pct(s['wer_ci95'][0])}-{pct(s['wer_ci95'][1])}) "
                f"| {pct(s['cer'])} ({pct(s['cer_ci95'][0])}-{pct(s['cer_ci95'][1])}) | {rtf} |\n")

    def ckpt_of(name: str) -> str:
        m = scores[name]["meta"]
        if m.get("checkpoint"):
            return f"`{m['checkpoint']}` @ `{str(m.get('revision', ''))[:10]}`"
        return m.get("setup", "")

    lines = [f"# Results on the {args.split} split\n\n",
             f"{len(refs)} clips, {sum(len(normalize_for_scoring(t).split()) for t in refs.values())} reference words. "
             "Generated by `scripts/score.py`; do not edit by hand.\n\n",
             "## 1. Baselines: published checkpoints, no training by our group\n\n", HEAD]
    for b in listed:
        if b.get("trained_by_us"):
            continue
        name = b["system"]
        if name in scores:
            lines.append(row(name, b["family"], ckpt_of(name)))
        else:
            why = b.get("reason", b.get("status", "not run"))
            link = f" [model card]({b['model_card']})" if b.get("model_card") else ""
            lines.append(f"| {name} | {b['family']} | `{b.get('checkpoint', '-')}` | not run: {why}{link} | | |\n")

    lines += ["\n## 2. Course baselines that we implemented and trained ourselves\n\n", HEAD]
    for b in listed:
        if b.get("trained_by_us"):
            name = b["system"]
            lines.append(row(name, b["family"], ckpt_of(name)) if name in scores
                         else f"| {name} | {b['family']} | | not run yet | | |\n")

    ours = sorted(k for k, v in scores.items() if v["meta"].get("kind") == "ours")
    lines += ["\n## 3. Our contribution: our own fine-tuning\n\n", HEAD]
    lines += [row(n, scores[n]["meta"].get("family", ""), ckpt_of(n)) for n in ours] or ["| - | | | not run yet | | |\n"]

    if scores:
        lines += ["\n## 4. Important words (W9 slide 13): recall of reference words by category\n\n",
                  "| System | All words | Names | Negation | Most missed names |\n|---|---|---|---|---|\n"]
        for name, s in scores.items():
            c = s["categories"]
            f = lambda k: f"{pct(c[k]['recall'])} ({c[k]['ref_words']})" if c[k]["recall"] is not None else "-"  # noqa: E731
            missed = ", ".join(f"{w} ×{n}" for w, n in c["most_missed_names"][:5])
            lines.append(f"| {name} | {f('all')} | {f('name')} | {f('negation')} | {missed} |\n")

    with_sil = [n for n, s in scores.items() if "silence" in s]
    if with_sil:
        lines += ["\n## 5. No-speech clips (W9 slide 44): output on silence and noise\n\n",
                  "| System | Clips with any output | Words emitted | Audio (s) |\n|---|---|---|---|\n"]
        for n in with_sil:
            v = scores[n]["silence"]
            lines.append(f"| {n} | {v['clips_with_output']} / {v['clips']} | {v['words_emitted']} | {v['seconds']} |\n")

    (RESULTS / f"RESULTS.{args.split}.md").write_text("".join(lines), encoding="utf-8")
    print("".join(lines))


if __name__ == "__main__":
    main()
